test("init and canonical invalidation reset the production registry without deleting physical assets",async()=>{
  const tmp=resolve(root,"tests/.tmp-registry-reset");
  await rm(tmp,{recursive:true,force:true});
  await mkdir(resolve(tmp,"assets/voice"),{recursive:true});
  await writeFile(resolve(tmp,"assets/voice/old.mp3"),validMp3);
  await writeFile(resolve(tmp,"assets/manifest.json"),JSON.stringify({version:"1",assets:[{id:"old",publicPath:"/assets/voice/old.mp3",type:"audio/mpeg",source:"old",sceneIds:["scene-1"],role:"voiceover"}]}),"utf8");
  await new Promise<void>((resolvePromise,reject)=>execFile(process.argv[0],[resolve(root,"dist/src/cli.js"),"init"],{cwd:tmp},error=>error?reject(error):resolvePromise()));
  const p=harnessPaths(tmp);
  assert.deepEqual(await readFile(p.assetManifest,"utf8").then(JSON.parse),{version:"1",assets:[]});
  assert.equal((await readFile(resolve(tmp,"assets/voice/old.mp3"))).length,validMp3.length);
  await writeFile(p.assetManifest,JSON.stringify({version:"1",assets:[{id:"old",publicPath:"/assets/voice/old.mp3",type:"audio/mpeg",source:"old",sceneIds:["scene-1"],role:"voiceover"}]}),"utf8");
  await invalidateProjectDerived(tmp);
  assert.deepEqual(await readFile(p.assetManifest,"utf8").then(JSON.parse),{version:"1",assets:[]});
  assert.equal((await readFile(resolve(tmp,"assets/voice/old.mp3"))).length,validMp3.length);
  await rm(tmp,{recursive:true,force:true});
});

